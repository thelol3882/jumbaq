// Generates src/shared/api/schema.d.ts from the backend's OpenAPI document.
// The document comes from the FastAPI app itself (no database needed), so the
// types always match the backend code in this repo.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";

const dump = "import json; from jumbaq.main import create_app; print(json.dumps(create_app().openapi()))";
const schema = execFileSync("uv", ["run", "--project", "../../backend", "python", "-c", dump], {
  encoding: "utf8",
});

const ast = await openapiTS(JSON.parse(schema));
writeFileSync("src/shared/api/schema.d.ts", `// Generated by \`pnpm api:types\`. Do not edit.\n\n${astToString(ast)}`);
